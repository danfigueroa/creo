-- Catálogo curado de versículos que alimenta o "versículo do dia".
--
-- A curadoria (referência + tema + tradição) vive aqui porque nenhuma API
-- pública da Bíblia sabe responder "um versículo sobre esperança" — elas só
-- resolvem referência -> texto. Já o texto fica nulo de propósito: é hidratado
-- sob demanda pelo internal/bible.TextProvider na primeira leitura e persistido
-- em text/fetched_at, o que mantém esta migration leve para o pooler do
-- Supabase (:6543) e permite trocar de tradução sem migration nova.
--
-- Exceção: os deuterocanônicos já vêm com texto, porque as traduções pt-BR
-- gratuitas servem apenas o cânon protestante e nunca conseguiriam hidratá-los.

DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'verse_theme') THEN
        CREATE TYPE verse_theme AS ENUM (
            'HOPE', 'GRIEF', 'GRATITUDE', 'FORGIVENESS', 'FAITH', 'FAMILY',
            'HEALING', 'PROVISION', 'COURAGE', 'PEACE', 'GUIDANCE', 'LOVE'
        );
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS bible_verses (
    id          UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    book_slug   TEXT NOT NULL,
    book_name   TEXT NOT NULL,
    chapter     INT NOT NULL CHECK (chapter > 0),
    verse       INT NOT NULL CHECK (verse > 0),
    theme       verse_theme NOT NULL,
    tradition   tradition,
    translation TEXT NOT NULL DEFAULT 'almeida',
    text        TEXT,
    fetched_at  TIMESTAMPTZ,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    deleted_at  TIMESTAMPTZ,
    UNIQUE (book_slug, chapter, verse, translation)
);

COMMENT ON COLUMN bible_verses.book_slug IS 'Chave do livro para a API de texto (ex.: "john", "1 samuel").';
COMMENT ON COLUMN bible_verses.book_name IS 'Nome do livro em pt-BR, para exibição (ex.: "João").';
COMMENT ON COLUMN bible_verses.tradition IS 'NULL serve as duas tradições; preenchido restringe o versículo a uma.';
COMMENT ON COLUMN bible_verses.text      IS 'Hidratado da API na primeira leitura; NULL enquanto não buscado.';

-- Ordem estável para o OFFSET determinístico da seleção diária, e cobre o
-- filtro de tradição do pool.
CREATE INDEX IF NOT EXISTS idx_bible_verses_pool
    ON bible_verses (tradition, id)
    WHERE deleted_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_bible_verses_theme
    ON bible_verses (theme, id)
    WHERE deleted_at IS NULL;

